// Exercise the actual packaged identities/encodings at a nested deployment prefix.
import { deepStrictEqual as equal, match } from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { chromium } from "playwright";
import { rendererAssets, resourceAssets, verifyDelivery } from "../scripts/precompress.mjs";
import { fixtures } from "./studies/bundle/fixtures.mjs";

const root = resolve(import.meta.dir, ".."), delivery = resolve(root, "artifacts/delivery");
verifyDelivery(delivery);
const pdfs = { ...fixtures(root), p250: readFileSync(resolve(root, "fixtures/p250.pdf")) };
const prefix = "/test/v1/";
const files = new Set([...rendererAssets, ...resourceAssets]);
let requests = [], fault, codec = "br";
const server = Bun.serve({ hostname: "127.0.0.1", port: 0, fetch(req) {
  const path = new URL(req.url).pathname;
  if (path === "/") return new Response("<!doctype html>", { headers: { "Content-Type": "text/html" } });
  if (path === "/no-worker-2d.js") return new Response(
    'OffscreenCanvas.prototype.getContext = () => null; await import("/test/v1/wasm-worker.js");',
    { headers: { "Content-Type": "text/javascript" } });
  if (path.startsWith("/pdf/") && Object.hasOwn(pdfs, path.slice(5)))
    return new Response(pdfs[path.slice(5)], { headers: { "Content-Type": "application/pdf" } });
  const file = path.slice(prefix.length);
  if (!path.startsWith(prefix) || !files.has(file)) return new Response(null, { status: 404 });
  if (resourceAssets.includes(file)) requests.push(file);
  if (file === fault?.file && fault.kind === "missing") return new Response(null, { status: 404 });
  const headers = { "Cache-Control": "no-store", "Content-Type":
    file.endsWith(".js") ? "text/javascript" : file.endsWith(".wasm") ? "application/wasm" : "application/octet-stream" };
  if (file === fault?.file && fault.kind === "corrupt") {
    const bytes = readFileSync(resolve(delivery, file));
    bytes[0] ^= 0xff;
    return new Response(bytes, { headers });
  }
  const suffix = codec === "identity" ? "" : codec === "br" ? ".br" : ".gz";
  if (suffix) headers["Content-Encoding"] = codec;
  return new Response(readFileSync(resolve(delivery, file + suffix)), { headers });
} });
let browser;
try {
  browser = await chromium.launch();
  const p = await browser.newPage();
  await p.goto(server.url.href);
  async function render(pdf) {
    requests = [];
    return p.evaluate(async pdf => {
      const { openDocument } = await import("/test/v1/wasm-engine.js");
      const doc = await openDocument(`/pdf/${pdf}`);
      const c = document.createElement("canvas"), ctx = c.getContext("2d");
      c.width = c.height = 1;
      ctx.fillStyle = "#123456"; ctx.fillRect(0, 0, 1, 1);
      try {
        await doc.render(1, 900, c);
        const pixels = ctx.getImageData(0, 0, c.width, c.height).data;
        const hash = new Uint8Array(await crypto.subtle.digest("SHA-256", pixels));
        return Array.from(hash, n => n.toString(16).padStart(2, "0")).join("");
      } catch (e) {
        return { error: String(e), dimensions: [c.width, c.height],
          firstPixel: Array.from(ctx.getImageData(0, 0, 1, 1).data) };
      } finally { doc.destroy(); }
    }, pdf);
  }
  // Baseline hashes from the fully embedded renderer, not images regenerated by this build.
  const glyphs = "0c81d399e0bfc264125cd0c26b924e14c3c75a2e409160e53166cab955d4b22d";
  const allFonts = "d53ac4f7cab7a83cb574a52b4ec3663a7c6ffc05e4961b655ea9b59d2e563aaf";
  equal(await render("p250"), "a715b2698189135ef51b0398ee300f52b23e2bd0bd4c263453c6dfed90506cf3");
  equal(requests, []);
  equal(await render("identity"), glyphs);
  equal(requests, []);
  equal(await render("base14"), allFonts);
  equal(requests.sort(), [...resourceAssets.slice(1)].sort());
  for (codec of ["br", "gzip", "identity"]) {
    equal(await render("jis"), glyphs);
    equal(requests, [resourceAssets[0]]);
  }
  for (const [pdf, id, kind, expected] of [["jis", 0, "missing", glyphs], ["base14", 1, "corrupt", allFonts]]) {
    fault = { file: resourceAssets[id], kind };
    const result = await render(pdf);
    match(result.error, new RegExp(`Invalid renderer asset ${id}`));
    equal(result.dimensions, [1, 1]); equal(result.firstPixel, [18, 52, 86, 255]);
    fault = null;
    equal(await render(pdf), expected, "Reopening should retry the failed asset");
  }
  // Legacy unflagged requests, small flagged requests and a worker without a
  // 2D context must use RGBA. A real 1600px bitmap must match RGBA byte-for-byte.
  const checkFrame = async (workerURL, width, bitmap) => p.evaluate(async ({ workerURL, width, bitmap }) => {
    const worker = new Worker(workerURL, { type: "module" });
    function rpc(data) {
      return new Promise((resolve, reject) => {
        worker.onmessage = e => e.data.fatal || e.data.error ? reject(Error(e.data.fatal || e.data.error)) : resolve(e.data);
        worker.onerror = e => reject(Error(e.message));
        worker.postMessage(data);
      });
    }
    try {
      const module = await WebAssembly.compileStreaming(fetch("/test/v1/pkg/folio_wasm.wasm"));
      worker.postMessage({ type: "code", module });
      await rpc({ type: "open", id: 1, url: "/pdf/jis" });
      const frame = await rpc({ type: "render", id: 2, page: 1, width, ...bitmap });
      let pixels = frame.pixels;
      if (frame.bitmap) {
        const c = document.createElement("canvas"); c.width = width; c.height = frame.height;
        const ctx = c.getContext("2d");
        try { ctx.drawImage(frame.bitmap, 0, 0); } finally { frame.bitmap.close(); }
        pixels = ctx.getImageData(0, 0, c.width, c.height).data;
      }
      return { bitmap: !!frame.bitmap, hash: Array.from(new Uint8Array(await crypto.subtle.digest("SHA-256", pixels))) };
    } finally { worker.terminate(); }
  }, { workerURL, width, bitmap });
  const worker = prefix + "wasm-worker.js";
  equal((await checkFrame(worker, 1599, { bitmap: true })).bitmap, false);
  const reference = await checkFrame(worker, 1600, {});
  equal(reference.bitmap, false);
  equal(await checkFrame(worker, 1600, { bitmap: true }), { ...reference, bitmap: true });
  equal(await checkFrame("/no-worker-2d.js", 1600, { bitmap: true }), reference);
  console.log("PASS: 1600px worker bitmap equals RGBA; 1599px, unflagged and no-worker-2D RGBA fallbacks");
  console.log("PASS: invoice, Identity-H, Base-14 and named JIS canvas SHA-256; lazy requests, 3 codecs, failure/reopen");
} finally {
  await browser?.close();
  server.stop(true);
}
